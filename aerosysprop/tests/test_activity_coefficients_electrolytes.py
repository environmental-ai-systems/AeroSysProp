"""Regression tests for AIOMFAC full SR + MR + LR (electrolyte) implementation.

Reference outputs in ``aiomfac_electrolyte_fixtures.json`` were generated by
running the public AIOMFAC Fortran code on water + neutral organic + salt
mixtures across a range of concentrations. Fortran reports neutral
activity coefficients on a mole-fraction basis (a_coeff_x) and ion activity
coefficients on a molality basis (a_coeff_m); our Python implementation
matches both conventions.

Tolerance: 5e-5 relative (the precision of the 5-6 sig-fig Fortran printed
output).

Re-run ``python aerosysprop/tests/generate_aiomfac_electrolyte_fixtures.py``
to refresh the JSON.
"""

import json
from pathlib import Path

import numpy as np
import pytest

from aerosysprop.methods.activity_coefficients import (
    AIOMFAC,
    aiomfac_from_smiles,
)


_FIXTURE_FILE = Path(__file__).parent / 'aiomfac_electrolyte_fixtures.json'
with _FIXTURE_FILE.open() as _f:
    _FIXTURES = json.load(_f)


def _decode_neutrals(fixture):
    return [
        {int(k): v for k, v in r['subgroups'].items()}
        for r in fixture['neutrals']
    ]


def _expected_per_kind(species):
    """Group a fixture's species list by kind and align with the order
    AIOMFAC.gamma returns (neutrals, cations, anions)."""
    neutrals = [s for s in species if s['kind'] == 'neutral']
    cations  = [s for s in species if s['kind'] == 'cation']
    anions   = [s for s in species if s['kind'] == 'anion']
    return neutrals, cations, anions


_IDS = [f['case_id'] for f in _FIXTURES]


@pytest.mark.parametrize('fixture', _FIXTURES, ids=_IDS)
def test_aiomfac_matches_fortran_dict_input(fixture):
    """Activity coefficients from AIOMFAC built with explicit neutral subgroup
    dicts must match Fortran for every composition point in the fixture."""
    neutral_dicts = _decode_neutrals(fixture)
    salts = fixture['salts']
    T_K = fixture['T_K']
    system = AIOMFAC(neutral_dicts, salts=salts)

    expected_n, expected_c, expected_a = _expected_per_kind(fixture['species'])
    component_names_in_order = (
        [r['name'] for r in fixture['neutrals']] + list(salts)
    )
    for pt_idx, row in enumerate(fixture['mass_fractions_rows']):
        wtf = [row[name] for name in component_names_in_order]
        result = system.gamma(wtf, T_K)

        # Compare neutrals (mole-fraction-basis gamma)
        for i, sp in enumerate(expected_n):
            x_fort, m_fort, gamma_fort = sp['x_m_gamma'][pt_idx]
            np.testing.assert_allclose(
                result.gamma_neutral[i], gamma_fort, rtol=5e-5, atol=0,
                err_msg=f'{fixture["case_id"]} pt {pt_idx+1}: gamma_x[{sp["name"]}]',
            )
        # Compare cations (molality basis)
        for i, sp in enumerate(expected_c):
            _, _, gamma_fort = sp['x_m_gamma'][pt_idx]
            np.testing.assert_allclose(
                result.gamma_cation[i], gamma_fort, rtol=5e-5, atol=0,
                err_msg=f'{fixture["case_id"]} pt {pt_idx+1}: gamma_m[{sp["name"]}]',
            )
        # Compare anions (molality basis)
        for i, sp in enumerate(expected_a):
            _, _, gamma_fort = sp['x_m_gamma'][pt_idx]
            np.testing.assert_allclose(
                result.gamma_anion[i], gamma_fort, rtol=5e-5, atol=0,
                err_msg=f'{fixture["case_id"]} pt {pt_idx+1}: gamma_m[{sp["name"]}]',
            )


@pytest.mark.parametrize('fixture', _FIXTURES, ids=_IDS)
def test_aiomfac_matches_fortran_smiles_input(fixture):
    """Same as the dict-input check, but via the SMILES entry point. Catches
    drift in groups.aiomfac() decomposition."""
    smiles = [r['smiles'] for r in fixture['neutrals']]
    salts = fixture['salts']
    T_K = fixture['T_K']

    expected_n, expected_c, expected_a = _expected_per_kind(fixture['species'])
    component_names_in_order = (
        [r['name'] for r in fixture['neutrals']] + list(salts)
    )
    for pt_idx, row in enumerate(fixture['mass_fractions_rows']):
        wtf = [row[name] for name in component_names_in_order]
        result = aiomfac_from_smiles(smiles, salts, wtf, T_K)

        for i, sp in enumerate(expected_n):
            _, _, gamma_fort = sp['x_m_gamma'][pt_idx]
            np.testing.assert_allclose(
                result.gamma_neutral[i], gamma_fort, rtol=5e-5, atol=0,
                err_msg=f'{fixture["case_id"]} pt {pt_idx+1} SMILES: gamma_x[{sp["name"]}]',
            )
        for i, sp in enumerate(expected_c):
            _, _, gamma_fort = sp['x_m_gamma'][pt_idx]
            np.testing.assert_allclose(
                result.gamma_cation[i], gamma_fort, rtol=5e-5, atol=0,
                err_msg=f'{fixture["case_id"]} pt {pt_idx+1} SMILES: gamma_m[{sp["name"]}]',
            )
        for i, sp in enumerate(expected_a):
            _, _, gamma_fort = sp['x_m_gamma'][pt_idx]
            np.testing.assert_allclose(
                result.gamma_anion[i], gamma_fort, rtol=5e-5, atol=0,
                err_msg=f'{fixture["case_id"]} pt {pt_idx+1} SMILES: gamma_m[{sp["name"]}]',
            )


def test_mean_ionic_definition():
    """Mean ionic gamma_+- = (gamma_c^nu_c * gamma_a^nu_a)^(1/(nu_c+nu_a))."""
    result = aiomfac_from_smiles(['O'], ['Na2SO4'], [0.95, 0.05], 298.15)
    gc = result.gamma_cation[0]  # Na+
    ga = result.gamma_anion[0]   # SO4^2-
    nu_c, nu_a = 2.0, 1.0
    expected = (gc ** nu_c * ga ** nu_a) ** (1.0 / (nu_c + nu_a))
    np.testing.assert_allclose(result.gamma_mean[0], expected, rtol=1e-12)


def test_zero_salt_reduces_to_SR():
    """When mass_fractions for all salts are 0, gamma_neutral should equal
    the SR-only result at the equivalent mole-fraction composition."""
    from aerosysprop.methods.activity_coefficients import (
        aiomfac_sr_from_smiles, AIOMFAC,
    )
    from aerosysprop import data, groups
    from rdkit import Chem
    # 50:50 mass fractions of water + ethanol -> equivalent mole fractions
    M_w = sum(data.AIOMFAC_MASS[k] * v
              for k, v in groups.aiomfac(Chem.MolFromSmiles('O')).items())
    M_e = sum(data.AIOMFAC_MASS[k] * v
              for k, v in groups.aiomfac(Chem.MolFromSmiles('CCO')).items())
    n_w = 0.5 / M_w; n_e = 0.5 / M_e
    x_w = n_w / (n_w + n_e); x_e = n_e / (n_w + n_e)

    res_full = aiomfac_from_smiles(['O', 'CCO'], ['NaCl'], [0.5, 0.5, 0.0], 298.15)
    res_sr   = aiomfac_sr_from_smiles(['O', 'CCO'], [x_w, x_e], 298.15)
    np.testing.assert_allclose(res_full.gamma_neutral, res_sr, rtol=1e-8)
