"""Regression tests for AIOMFAC short-range activity coefficients.

Reference outputs in ``aiomfac_sr_fixtures.json`` were generated by running the
public AIOMFAC Fortran code (https://github.com/andizuend/AIOMFAC) on the
binary water+organic mixtures and multi-component mixtures specified in
``generate_aiomfac_sr_fixtures.py``. With no ions present, the AIOMFAC MR + LR
contributions are identically zero and ``a_coeff_x`` in the Fortran output
equals the SR term we compute here.

The Fortran output prints 5-6 significant figures, which sets the achievable
tolerance for this comparison (rtol = 5e-5).

Re-run ``python aerosysprop/tests/generate_aiomfac_sr_fixtures.py`` to refresh
the JSON when the curated list, parameters, or matcher changes.
"""

import json
from pathlib import Path

import numpy as np
import pytest

from aerosysprop.methods.activity_coefficients import (
    AIOMFAC_SR,
    aiomfac_sr_from_smiles,
)


_FIXTURE_FILE = Path(__file__).parent / 'aiomfac_sr_fixtures.json'

with _FIXTURE_FILE.open() as _f:
    _ALL_FIXTURES = json.load(_f)


def _decode_subgroups(record):
    """JSON stringifies dict keys; convert subgroup IDs back to int."""
    return {int(k): v for k, v in record['subgroups'].items()}


def _fixture_components(fixture):
    return [_decode_subgroups(c) for c in fixture['components']]


def _fixture_smiles(fixture):
    return [c['smiles'] for c in fixture['components']]


_FIXTURE_IDS = [f['case_id'] for f in _ALL_FIXTURES]


@pytest.mark.parametrize('fixture', _ALL_FIXTURES, ids=_FIXTURE_IDS)
def test_sr_matches_fortran(fixture):
    """Activity coefficients from our Python SR implementation must match the
    Fortran reference at every composition point, for every fixture."""
    components = _fixture_components(fixture)
    T_K = fixture['T_K']
    system = AIOMFAC_SR(components)
    x_ref = np.array(fixture['x'])
    gamma_ref = np.array(fixture['gamma'])
    for x_row, gamma_row in zip(x_ref, gamma_ref):
        gamma_py = system.gamma(x_row, T_K)
        np.testing.assert_allclose(gamma_py, gamma_row, rtol=5e-5, atol=0)


@pytest.mark.parametrize('fixture', _ALL_FIXTURES, ids=_FIXTURE_IDS)
def test_sr_smiles_pipeline_matches_fortran(fixture):
    """The SMILES-driven entry point must produce the same numbers, catching
    drift in groups.aiomfac() or in any pre-processing in the pipeline."""
    smiles = _fixture_smiles(fixture)
    T_K = fixture['T_K']
    x_ref = np.array(fixture['x'])
    gamma_ref = np.array(fixture['gamma'])
    for x_row, gamma_row in zip(x_ref, gamma_ref):
        gamma_py = aiomfac_sr_from_smiles(smiles, x_row, T_K)
        np.testing.assert_allclose(gamma_py, gamma_row, rtol=5e-5, atol=0)


def test_pure_component_limit_is_one():
    """gamma_i -> 1 at x_i -> 1 for every component, by construction."""
    # Use a mid-complexity ternary fixture from the suite
    fixture = next(
        f for f in _ALL_FIXTURES
        if f['case_id'] == 'multi__water_ethanol_ethyleneglycol'
    )
    components = _fixture_components(fixture)
    system = AIOMFAC_SR(components)
    n = len(components)
    for i in range(n):
        x = np.full(n, 1e-9)
        x[i] = 1.0 - (n - 1) * 1e-9
        gamma = system.gamma(x, fixture['T_K'])
        assert abs(gamma[i] - 1.0) < 1e-6


def test_all_fixtures_loaded():
    """Sanity check that the fixture file is non-empty and well-formed."""
    assert len(_ALL_FIXTURES) >= 30
    binaries = [f for f in _ALL_FIXTURES if f['kind'] == 'binary']
    multis = [f for f in _ALL_FIXTURES if f['kind'] == 'multi']
    assert len(binaries) >= 25
    assert len(multis) >= 3
